
CREATE TABLE course (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    course_id BIGINT NOT NULL,
    CONSTRAINT fk_student_course
        FOREIGN KEY (course_id)
        REFERENCES course(id)
);
